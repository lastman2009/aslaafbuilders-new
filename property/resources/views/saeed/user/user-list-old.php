<script>
    $(document).ready(function () {

        $(function () {
            $('.toggle-icon').click(function () {
                $(this).find('i').toggleClass('fa-unlock fa-lock');
            });
        });

        $('.toggle-icon').click(function () {
            if ($('.status-user').text() == 'Active')
            {
                $('.status-user').text('Blocked').removeClass('active-text').addClass('blocked-text');
            } else
            {
                $('.status-user').text('Active').removeClass('blocked-text').addClass('active-text');
            }
        });

    });

</script>